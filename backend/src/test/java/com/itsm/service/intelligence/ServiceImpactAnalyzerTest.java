package com.itsm.service.intelligence;

import com.itsm.domain.ITService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

// Same shape as the seeded graph, including the cycle DNS -> Monitoring -> Network -> DNS.
class ServiceImpactAnalyzerTest {

    private final ServiceImpactAnalyzer analyzer = new ServiceImpactAnalyzer();
    private ITService dns, network, sso, email, lms, erp, db, payroll, monitoring;
    private List<ITService> all;

    // Ids are normally generated by the database; tests set them through reflection.
    private static ITService service(String name, long id) {
        ITService s = new ITService(name, 2);
        ReflectionTestUtils.setField(s, "id", id);
        return s;
    }

    @BeforeEach
    void buildGraph() {
        dns = service("DNS", 1);
        network = service("Network", 2);
        sso = service("SSO", 3);
        email = service("Email", 4);
        lms = service("LMS", 5);
        erp = service("ERP", 6);
        db = service("Database", 7);
        payroll = service("Payroll", 8);
        monitoring = service("Monitoring", 9);
        network.addDependency(dns);
        sso.addDependency(network);
        email.addDependency(sso);
        lms.addDependency(sso);
        erp.addDependency(sso);
        erp.addDependency(db);
        payroll.addDependency(erp);
        monitoring.addDependency(network);
        dns.addDependency(monitoring);
        all = List.of(dns, network, sso, email, lms, erp, db, payroll, monitoring);
    }

    private static Map<String, Integer> distances(List<ImpactedService> impacted) {
        Map<String, Integer> result = new HashMap<>();
        for (ImpactedService item : impacted) {
            result.put(item.service().getName(), item.distance());
        }
        return result;
    }

    @Test
    void databaseOutageImpactsErpThenPayroll() {
        assertEquals(Map.of("ERP", 1, "Payroll", 2), distances(analyzer.analyze(db, all)));
    }

    @Test
    void leafServiceImpactsNothing() {
        assertTrue(analyzer.analyze(payroll, all).isEmpty());
    }

    @Test
    void networkOutageFollowsTheCycleOnceAndStops() {
        Map<String, Integer> d = distances(analyzer.analyze(network, all));
        assertEquals(Map.of("SSO", 1, "Monitoring", 1, "Email", 2, "LMS", 2, "ERP", 2, "DNS", 2, "Payroll", 3), d);
        assertFalse(d.containsKey("Network")); // the cycle leads back to Network, which is skipped
    }

    @Test
    void outageAsADifferentObjectWithTheSameIdIsStillMatched() {
        // Like an entity loaded in another persistence context: same row (id 2), different Java object.
        ITService networkCopy = service("Network", 2);
        Map<String, Integer> d = distances(analyzer.analyze(networkCopy, all));
        assertEquals(7, d.size());
        assertEquals(1, d.get("SSO"));
        assertFalse(d.containsKey("Network")); // excluded by id, even though the object differs
    }
}
